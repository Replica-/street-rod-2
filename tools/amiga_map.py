"""Which Amiga picture replaces which PC picture (--amiga): candidate pairs for sr2port/src/enh/amiga_map.h.

  python tools/amiga_map.py [--report work/amiga_map.txt]

For every PC picture (LIB1 / LIB2 / LIB3, ids 1.. / 1000.. / 2000..) the Amiga pictures of the same size (lib.p,
libstart.p) are compared in all 10 palette tables of STREET_ROD: the shape must agree (correlation of the brightness
of the two pictures, PC in the game palette DS:1DC8), then the palette table whose colours come closest to the PC
picture's wins (a hint: the game picks it at run time). Writes candidates to work/; the real table
sr2port/src/enh/amiga_map.h is curated by eye from them. Needs Game/ (LIB1-3) and Game/amiga (the extracted .adf disks); the table holds only numbers.
"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import srlib, amilib

MIN_CORR = 0.55
EXE = 'Game/amiga/disk1/STREET_ROD'


def amiga_palettes():
    d = open(EXE, 'rb').read()
    pals = []
    for k in range(10):
        w = struct.unpack_from('>32H', d, 0x3C904 + 64 * k)
        p = [((x >> 8 & 15) * 17, (x >> 4 & 15) * 17, (x & 15) * 17) for x in w]
        pals.append(p + [(r // 2, g // 2, b // 2) for r, g, b in p])
    return pals


def lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def corr(a, b):
    n = len(a)
    ma, mb = sum(a) / n, sum(b) / n
    va = sum((x - ma) ** 2 for x in a)
    vb = sum((y - mb) ** 2 for y in b)
    if va < 1e-6 or vb < 1e-6:
        return 0.0
    return sum((x - ma) * (y - mb) for x, y in zip(a, b)) / (va * vb) ** 0.5


def sample(w, h, step):
    return [(x, y) for y in range(0, h, step) for x in range(0, w, step)]


def main():
    report = sys.argv[sys.argv.index('--report') + 1] if '--report' in sys.argv else None
    pcpal = srlib.game_palette(0x1DC8)
    pals = amiga_palettes()
    amiga = []                                  # (lib 0 = lib.p / 1 = libstart.p, index, w, h, colour indices)
    for li, path in enumerate(('Game/amiga/disk2/lib.p', 'Game/amiga/disk1/libstart.p')):
        for p in amilib.read(path):
            raw = amilib.unpack(p)
            amiga.append((li, p['index'], p['w'], p['h'], amilib.indices(p, raw)))
    rows, lines = [], []
    for lib, base in (('LIB1', 1), ('LIB2', 1000), ('LIB3', 2000)):
        for p in srlib.read_lib('Game/' + lib):
            pid = base + p['index']
            idx = srlib.to_indices(p, srlib.unpack(p['data'], p['tokens'], p['raw'], p['sr2']))
            cands = [a for a in amiga if a[2] == p['w'] and a[3] == p['h']]
            if not cands:
                continue
            step = max(1, int((p['w'] * p['h'] / 4000) ** 0.5))
            pts = sample(p['w'], p['h'], step)
            pc_rgb = [pcpal[idx[y * p['w'] + x]] for x, y in pts]
            pc_l = [lum(c) for c in pc_rgb]
            best = None
            for li, ai, w, h, aidx in cands:
                for k, pal in enumerate(pals):
                    am = [pal[aidx[y * w + x] % len(pal)] for x, y in pts]
                    c = corr(pc_l, [lum(q) for q in am])
                    dist = sum(abs(a[0] - b[0]) + abs(a[1] - b[1]) + abs(a[2] - b[2]) for a, b in zip(pc_rgb, am)) / len(am)
                    key = (c > MIN_CORR, -dist if c > MIN_CORR else c)
                    if best is None or key > best[0]:
                        best = (key, li, ai, k, c, dist)
            ok = best[4] > MIN_CORR
            lines.append('%-5s #%-3d id %4d %3dx%-3d -> %s #%-3d pal %d corr %.2f dist %5.1f %s' % (
                lib, p['index'], pid, p['w'], p['h'], 'lib.p' if best[1] == 0 else 'libstart.p', best[2], best[3],
                best[4], best[5], 'OK' if ok else '-'))
            if ok:
                rows.append((pid, best[1], best[2], best[3]))
    out = 'work/amiga_map_candidates.h'          # candidates; the table in sr2port/src/enh/amiga_map.h is checked by eye
    with open(out, 'w', newline='\n') as f:
        f.write('/* Generated by tools/amiga_map.py: PC picture id -> Amiga picture (lib 0 = disk2/lib.p, 1 = disk1/libstart.p,\n'
                ' * index, STREET_ROD palette table). Numbers only; the pictures are the user\'s own files. */\n')
        f.write('static const struct { short pc_id; unsigned char lib; short index; unsigned char pal; } amiga_map[] = {\n')
        for r in rows:
            f.write('    { %d, %d, %d, %d },\n' % r)
        f.write('};\n')
    if report:
        open(report, 'w').write('\n'.join(lines) + '\n')
    print('%d PC pictures with a same-size Amiga candidate, %d matched -> %s' % (len(lines), len(rows), out))


if __name__ == '__main__':
    main()
